def extract_local_slots(text: str) -> list[SlotName]:
    lowered = text.lower()
    found: list[SlotName] = []
    for slot, keywords in LOCAL_SLOT_KEYWORDS.items():
        if any(keyword.lower() in lowered for keyword in keywords):
            found.append(slot)
    return found
